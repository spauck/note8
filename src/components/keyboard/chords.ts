import type { Bar, Hand } from "@/lib/composer-state";
import { CHORD_PATTERNS, type ParsedNote } from "@/lib/scale";

/** A unique combination of notes with their hand assignments. */
export interface Chord {
  key: string;
  notes: Array<{ value: string; hand: Hand }>;
}

export function serializeChord(
  notes: Array<{ value: string; hand: Hand }>,
): string {
  return notes
    .map((n) => `${n.hand}:${n.value}`)
    .sort()
    .join("|");
}

/** Chord identity ignoring hand assignment — the set of note ids. */
function noteSetKey(notes: Array<{ value: string }>): string {
  return notes
    .map((n) => n.value)
    .sort()
    .join("|");
}

/** Extract every distinct multi-note beat across all bars. */
export function extractChords(bars: Bar[]): Chord[] {
  const seen = new Map<string, Chord>();
  for (const bar of bars) {
    for (const notes of bar.beats) {
      if (notes.length < 2) continue;
      const key = serializeChord(notes);
      if (!seen.has(key)) {
        seen.set(key, { key, notes });
      }
    }
  }
  return Array.from(seen.values());
}

/**
 * Build the chord list shown in the keyboard: every recognized chord that
 * can be played on the current scale (root taken from ding + scale notes),
 * merged with any chords already used in the composition. Notes default to
 * the "none" hand unless the composition uses a specific hand for that note.
 */
export function generateChords(
  bars: Bar[],
  ding: ParsedNote | null,
  scale: ParsedNote[],
): Chord[] {
  // Preferred hand per note-id, learned from the composition.
  const handCounts = new Map<string, Map<Hand, number>>();
  for (const bar of bars) {
    for (const beat of bar.beats) {
      for (const n of beat) {
        if (!handCounts.has(n.value)) handCounts.set(n.value, new Map());
        const m = handCounts.get(n.value)!;
        m.set(n.hand, (m.get(n.hand) ?? 0) + 1);
      }
    }
  }
  const preferredHand = (value: string): Hand => {
    const m = handCounts.get(value);
    if (!m || m.size === 0) return "none";
    let best: Hand = "none";
    let bestScore = -1;
    for (const [h, c] of m) {
      // Prefer explicit hands over "none" when counts tie.
      const score = c * 10 + (h === "none" ? 0 : 1);
      if (score > bestScore) {
        bestScore = score;
        best = h;
      }
    }
    return best;
  };

  // Note ids playable per pitch class ("0" = ding, "1..N" = scale positions).
  const idsByPc = new Map<number, string[]>();
  const addId = (pc: number, id: string) => {
    if (!idsByPc.has(pc)) idsByPc.set(pc, []);
    idsByPc.get(pc)!.push(id);
  };
  if (ding) addId(ding.pitchClass, "0");
  scale.forEach((n, i) => addId(n.pitchClass, String(i + 1)));

  const pickId = (pc: number): string | null => {
    const ids = idsByPc.get(pc);
    if (!ids || ids.length === 0) return null;
    // Prefer an id already used in the composition (keeps the hand).
    for (const id of ids) if (handCounts.has(id)) return id;
    return ids[0];
  };

  // Seed with composition chords so their hand assignments win.
  const bySetKey = new Map<string, Chord>();
  for (const c of extractChords(bars)) {
    bySetKey.set(noteSetKey(c.notes), c);
  }

  const rootPcs = Array.from(idsByPc.keys());
  const generated: Array<Chord & { rank: number }> = [];
  for (const root of rootPcs) {
    for (const pattern of CHORD_PATTERNS) {
      const noteIds: string[] = [];
      let ok = true;
      for (const iv of pattern.intervals) {
        const pc = (root + iv) % 12;
        const id = pickId(pc);
        if (!id) {
          ok = false;
          break;
        }
        noteIds.push(id);
      }
      if (!ok) continue;
      const uniqIds = Array.from(new Set(noteIds));
      if (uniqIds.length < 2) continue;
      const notes = uniqIds.map((v) => ({ value: v, hand: preferredHand(v) }));
      const setKey = noteSetKey(notes);
      if (bySetKey.has(setKey)) continue;
      const chord: Chord = { key: serializeChord(notes), notes };
      bySetKey.set(setKey, chord);
      generated.push({ ...chord, rank: pattern.rank });
    }
  }

  // Composition chords first (in original order), then generated by rank desc.
  const compChords = extractChords(bars).map((c) => bySetKey.get(noteSetKey(c.notes))!).filter(Boolean);
  const compKeys = new Set(compChords.map((c) => c.key));
  const rest = generated
    .filter((c) => !compKeys.has(c.key))
    .sort((a, b) => b.rank - a.rank)
    .map(({ rank: _r, ...c }) => c);
  return [...compChords, ...rest];
}

